#!/usr/bin/env node
'use strict';
//
// gen-request-flow-doc.js — regenerate the README request-flow step-through from
// the single source of truth: the SCENARIOS object inside docs/request-flow.html.
//
// Usage:
//   node tools/gen-request-flow-doc.js             # rewrite the marked README region
//   node tools/gen-request-flow-doc.js --check     # exit 1 + print a diff if README is stale
//
// Why this exists: the same three walkthroughs (happy path, failover, named pin)
// are told in two places — the interactive page and the README. They drifted once
// already: an endpoints.gemini_ai example carried fields (call_style, auth_env)
// that the shipped config does not have, and the fix had to be applied twice.
// The page is now authoritative and the README region is derived from it.
//
// Mirrors gen-routing-doc.js in shape and exit-code contract on purpose.
// Node stdlib only — no external deps (repo invariant).

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { execFileSync } = require('child_process');
const {
  expandLatestModel,
  isChineseOrigin,
  resolveModelRoute,
} = require('./model-map-resolve.js');

const REPO = path.resolve(__dirname, '..');
const README = path.join(REPO, 'README.md');
const PAGE = path.join(REPO, 'docs', 'request-flow.html');
const CONFIG = path.join(REPO, 'config', 'model-map.json');

const BEGIN = '<!-- BEGIN request-flow-steps (generated by tools/gen-request-flow-doc.js from docs/request-flow.html — run it, don\'t hand-edit) -->';
const END = '<!-- END request-flow-steps -->';
const MODES = ['best-cloud', 'best-cloud-oss', 'best-local-oss', 'best-cloud-gov', 'best-local-gov'];
const TIERS = ['16gb', '32gb', '48gb', '64gb', '128gb'];
const PASSTHROUGH = new Set(['WebSearch', 'WebFetch', 'Monitor']);

// Scenario key -> the heading shown in the README summary.
const TITLES = {
  happy: 'Happy path — coder, best-cloud-oss, 64gb',
  failover: 'Explicit Gemini failure — the cascade in payloads',
  pinned: 'Named agent — ask agent grok',
};
// Pipeline node id -> who is acting at that step.
const ACTORS = {
  you: 'You',
  harness: 'Claude Code harness',
  hook: 'PreToolUse hook',
  parse: 'claude-proxy',
  cap: 'claude-proxy',
  model: 'claude-proxy',
  endpoint: 'claude-proxy',
  upstream: 'Upstream API',
  back: 'claude-proxy',
  done: 'You',
};

// Extract the `var SCENARIOS = { ... }` object literal by brace matching, skipping
// braces that appear inside string literals, then evaluate it in an empty context.
function readScenarios(html) {
  const decl = html.indexOf('var SCENARIOS = {');
  if (decl === -1) {
    console.error(`gen-request-flow-doc: could not find "var SCENARIOS = {" in ${path.relative(REPO, PAGE)}.`);
    process.exit(2);
  }
  const from = html.indexOf('{', decl);
  let depth = 0;
  let end = -1;
  let quote = null;
  for (let i = from; i < html.length; i++) {
    const c = html[i];
    if (quote) {
      if (c === '\\') { i++; continue; }
      if (c === quote) quote = null;
      continue;
    }
    if (c === '"' || c === "'") { quote = c; continue; }
    if (c === '{') depth++;
    else if (c === '}') { depth--; if (depth === 0) { end = i + 1; break; } }
  }
  if (end === -1) {
    console.error('gen-request-flow-doc: SCENARIOS object literal is unterminated.');
    process.exit(2);
  }
  try {
    return vm.runInNewContext('(' + html.slice(from, end) + ')');
  } catch (err) {
    console.error('gen-request-flow-doc: SCENARIOS did not evaluate as an object literal: ' + err.message);
    process.exit(2);
  }
}

function displayFormat(raw) {
  if (raw === 'gemini') return 'Gemini';
  if (raw === 'openai') return 'OpenAI Responses';
  return 'Anthropic';
}

function explainAll(mode, tier) {
  const out = execFileSync('node', [path.join(REPO, 'tools', 'c-thru-explain.js'),
    '--all', '--mode', mode, '--tier', tier, '--format', 'json'], {
    env: { ...process.env, CLAUDE_MODEL_MAP_PATH: CONFIG },
    encoding: 'utf8',
    maxBuffer: 16 * 1024 * 1024,
  });
  return new Map(JSON.parse(out).map((row) => [row.capability, row]));
}

function resolveConcrete(model, config, mode) {
  const latest = expandLatestModel(model, config.latest_models) || model;
  const routed = resolveModelRoute(latest, {
    routes: config.model_routes || {},
    endpoints: config.endpoints || config.backends || {},
    mode,
    latest_models: config.latest_models || {},
  });
  return {
    requested: latest,
    model: (routed && routed.servedBy) || latest,
    endpoint: routed && routed.endpointId,
  };
}

// Keep the page's interactive resolver tied to the same shipped config and
// resolver used by the proxy/explain command. This data used to be pasted by
// hand and could remain plausibly wrong after a model-map migration.
function buildResolverData(config) {
  const byModeTier = new Map();
  for (const mode of MODES) {
    for (const tier of TIERS) byModeTier.set(`${mode}|${tier}`, explainAll(mode, tier));
  }

  const endpoints = {};
  for (const [id, endpoint] of Object.entries(config.endpoints || config.backends || {})) {
    endpoints[id] = {
      format: displayFormat(endpoint.format || endpoint.kind || 'anthropic'),
      fallback_to: endpoint.fallback_to || null,
    };
  }

  const agents = {};
  for (const [agent, capability] of Object.entries(config.agent_to_capability || {})) {
    if (PASSTHROUGH.has(agent)) continue;
    if (typeof capability === 'string' && capability.startsWith('model:')) {
      const rawPin = capability.slice('model:'.length);
      const resolved = resolveConcrete(rawPin, config, 'best-cloud');
      const entry = {
        capability,
        pin: resolved.requested,
        cells: {},
        endpoint: resolved.endpoint || (resolved.model.startsWith('claude-') ? 'anthropic' : 'ollama_local'),
        wire: resolved.model !== resolved.requested ? resolved.model : null,
      };
      if (isChineseOrigin(resolved.requested)) {
        entry.blocked_modes = ['best-cloud-gov', 'best-local-gov'];
      }
      agents[agent] = entry;
      continue;
    }

    const profile = (config.llm_profiles || {})[capability] || {};
    const cells = {};
    for (const mode of MODES) {
      for (const tier of TIERS) {
        const row = byModeTier.get(`${mode}|${tier}`).get(capability);
        if (!row || !row.model) continue;
        const resolved = resolveConcrete(row.model, config, mode);
        cells[`${mode}|${tier}`] = {
          model: resolved.model,
          endpoint: resolved.endpoint || row.endpoint_id,
          wire: resolved.model !== resolved.requested ? resolved.model : null,
        };
      }
    }
    agents[agent] = {
      capability,
      pin: null,
      cells,
      on_failure: profile.on_failure || 'cascade',
      fallback_to: profile.fallback_to || null,
    };
  }

  return { modes: MODES, tiers: TIERS, endpoints, agents };
}

function spliceResolverData(html, data) {
  const startToken = '  var R = ';
  const endToken = '\n\n  var PRETTY = {';
  const start = html.indexOf(startToken);
  const end = html.indexOf(endToken, start);
  if (start === -1 || end === -1) {
    console.error('gen-request-flow-doc: could not locate the embedded resolver data block in docs/request-flow.html.');
    process.exit(2);
  }
  return html.slice(0, start) + startToken + JSON.stringify(data) + ';' + html.slice(end);
}

// A leading "~" marks a changed line. Changed lines render as diff additions so
// GitHub tints them; a block with no changes stays a plain text fence.
function renderCode(step) {
  const lines = step.code.split('\n');
  const anyChanged = lines.some((l) => l.charAt(0) === '~');
  const out = ['```' + (anyChanged ? 'diff' : 'text')];
  const pad = anyChanged ? '  ' : '';
  if (step.cap) out.push(pad + '# ' + step.cap);
  for (const l of lines) {
    out.push(l.charAt(0) === '~' ? '+ ' + l.slice(1) : pad + l);
  }
  out.push('```');
  return out;
}

function buildSteps(scenarios) {
  const out = [];
  for (const key of ['happy', 'failover', 'pinned']) {
    const steps = scenarios[key];
    if (!Array.isArray(steps)) {
      console.error(`gen-request-flow-doc: scenario "${key}" is missing or not an array.`);
      process.exit(2);
    }
    out.push('<details>');
    out.push(`<summary><b>${TITLES[key]}</b> &mdash; ${steps.length} steps</summary>`);
    out.push('');
    steps.forEach((st, i) => {
      const actor = ACTORS[st.node] || st.node;
      out.push('<details>');
      out.push(`<summary>${i + 1} &middot; ${st.title} &mdash; <i>${actor}</i></summary>`);
      out.push('');
      out.push(st.body);
      if (st.code) {
        out.push('');
        out.push(...renderCode(st));
      }
      if (st.note) {
        out.push('');
        out.push('> ' + st.note);
      }
      out.push('');
      out.push('</details>');
      out.push('');
    });
    out.push('</details>');
    out.push('');
  }
  return out.join('\n').trim();
}

function spliceRegion(readme, body) {
  const b = readme.indexOf(BEGIN);
  const e = readme.indexOf(END);
  if (b === -1 || e === -1 || e < b) {
    console.error(`gen-request-flow-doc: sentinel markers not found in README.md.\n  Expected:\n    ${BEGIN}\n    ${END}`);
    process.exit(2);
  }
  const before = readme.slice(0, b + BEGIN.length);
  const after = readme.slice(e);
  return `${before}\n${body}\n${after}`;
}

function main() {
  const check = process.argv.includes('--check');
  const page = fs.readFileSync(PAGE, 'utf8');
  const config = JSON.parse(fs.readFileSync(CONFIG, 'utf8'));
  const nextPage = spliceResolverData(page, buildResolverData(config));
  const readme = fs.readFileSync(README, 'utf8');
  const next = spliceRegion(readme, buildSteps(readScenarios(nextPage)));

  if (check) {
    if (nextPage === page && next === readme) {
      console.log('gen-request-flow-doc: resolver data and README step-through are up to date.');
      return;
    }
    if (nextPage !== page) {
      console.error('gen-request-flow-doc: docs/request-flow.html resolver data is STALE (config/model-map.json changed).');
    }
    if (next === readme) process.exit(1);
    console.error('gen-request-flow-doc: README step-through is STALE (docs/request-flow.html changed but the README region was not regenerated).');
    const region = (s) => s.slice(s.indexOf(BEGIN), s.indexOf(END) + END.length).split('\n');
    const cur = region(readme);
    const gen = region(next);
    const max = Math.max(cur.length, gen.length);
    for (let i = 0; i < max; i++) {
      if (cur[i] !== gen[i]) {
        if (cur[i] !== undefined) console.error(`  - ${cur[i]}`);
        if (gen[i] !== undefined) console.error(`  + ${gen[i]}`);
      }
    }
    console.error('\nRun: node tools/gen-request-flow-doc.js');
    process.exit(1);
  }

  if (nextPage !== page) {
    fs.writeFileSync(PAGE, nextPage);
    console.log('gen-request-flow-doc: regenerated docs/request-flow.html resolver data.');
  }
  if (next !== readme) {
    fs.writeFileSync(README, next);
    console.log('gen-request-flow-doc: regenerated README step-through.');
  }
  if (nextPage === page && next === readme) {
    console.log('gen-request-flow-doc: resolver data and README step-through already current — no change.');
  }
}

main();

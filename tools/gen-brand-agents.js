#!/usr/bin/env node
'use strict';
/**
 * Generate fleet brand-leaf agents from config/brand-agents.json.
 *
 *   node tools/gen-brand-agents.js           # write agents/*.md + patch agent_to_capability
 *   node tools/gen-brand-agents.js --check   # exit 1 if generated content would drift
 *
 * Deletes stale catalog files only when they carry this generator's ownership marker.
 * Never overwrites or deletes non-generated agent files.
 */

const fs = require('fs');
const path = require('path');

const REPO = path.join(__dirname, '..');
const CATALOG_PATH = path.join(REPO, 'config', 'brand-agents.json');
const MAP_PATH = path.join(REPO, 'config', 'model-map.json');
const PLUGIN_MAP_PATH = path.join(REPO, 'plugins', 'c-thru', 'config', 'model-map.json');
const AGENTS_DIR = path.join(REPO, 'agents');

const ID_RE = /^[a-z][a-z0-9-]*$/;
const GENERATED_MARKER = '<!-- GENERATED by tools/gen-brand-agents.js; edits will be overwritten. -->';
const CHECK = process.argv.includes('--check');

function loadJson(p) {
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

function expandEntries(catalog) {
  const out = [];
  const seen = new Set();
  for (const agent of catalog.agents || []) {
    const primary = {
      id: agent.id,
      pin: agent.pin,
      family: agent.family || agent.id,
      label: agent.label || agent.id,
      triggers: agent.triggers || [],
      isAlias: false,
      primaryId: agent.id,
    };
    out.push(primary);
    seen.add(agent.id);
    for (const al of agent.aliases || []) {
      const id = typeof al === 'string' ? al : al.id;
      const pin = typeof al === 'string' ? agent.pin : (al.pin || agent.pin);
      if (seen.has(id)) {
        throw new Error(`duplicate brand agent id '${id}'`);
      }
      seen.add(id);
      out.push({
        id,
        pin,
        family: agent.family || agent.id,
        label: agent.label || agent.id,
        triggers: [`ask ${id}`, `use ${id}`, ...(agent.triggers || []).slice(0, 2)],
        isAlias: true,
        primaryId: agent.id,
      });
    }
  }
  return out;
}

function otherPrimaryNames(catalog, selfPrimaryId) {
  // Only primary short ids — never alias/full tags (description-quality scans for model-like tokens).
  return (catalog.agents || [])
    .map(a => a.id)
    .filter(id => id !== selfPrimaryId)
    .slice(0, 8);
}

function buildDescription(entry, catalog) {
  // Prefer short quoted triggers without versioned model tags / gemini-* tokens
  // (description-quality scans for model-id-like strings).
  const safeTriggers = (entry.triggers || [])
    .filter(t => !/[:.]/.test(t) && !/\d{4}/.test(t) && !/\bgemini-/i.test(t) && !/\bgpt-oss-/i.test(t))
    .slice(0, 4);
  if (entry.isAlias) {
    // Exact-id only; never embed bare primary name (poaches family asks).
    return (
      `MUST BE USED only when the user types the exact agent id "${entry.id}", character for character. ` +
      `Use for "ask ${entry.id}", "use ${entry.id}". ` +
      `Not for plain family-name asks — use the primary named agent instead. ` +
      `Not for multi-file implementation — use coder instead.`
    );
  }
  const id = entry.primaryId;
  const trig = safeTriggers.length
    ? safeTriggers.map(t => `"${t}"`).join(', ')
    : `"ask ${id}", "use ${id}"`;
  // Name-bound paraphrases only (not shared "second opinion" on every brand).
  const paraphrases = `"what would ${id} say", "${id}'s take"`;
  return (
    `MUST BE USED when the user names ${entry.label} — ${trig}, ${paraphrases}. ` +
    `Not for multi-file implementation — use coder instead. ` +
    `Not for a multi-model panel — use advisors instead.`
  );
}

function buildBody(entry) {
  const aliasLine = entry.isAlias
    ? `\nThis is a **full-name alias** of the primary brand leaf for family **${entry.family}**.\n`
    : '';
  // Do not embed concrete model tags (colons/dots) in the body — agent-description-quality
  // treats them as model-id claims that must match the pin's resolution set.
  return `# Agent: ${entry.label} (\`${entry.id}\`)

You are the c-thru **named brand leaf** for **${entry.label}**.
Routing is via \`agent_to_capability\` model pin for this agent name (see config brand catalog).
${aliasLine}
## Hard constraints

- Complete the task in this turn; return the answer to the parent.
- Prefer to complete the task yourself; avoid spawning further Agent/Task subagents for the same question.
- Do not re-delegate the same question to another agent.
- Prefer opinion, critique, and short analysis over multi-file source patches. If the ask is
  clearly an implement/fix/review-loop contract, say so and return to the parent so they can
  route to \`coder\` instead of half-applying edits here.

## Identity

- Report the model you are actually generating with.
- Do not invent "${entry.label}" from the agent name alone if routing failed.
- If you are not the intended brand family, say so plainly.

## Strategy

- Treat the user question as a one-shot brief: goal, scope (paths if given), constraints, and
  what a good answer looks like.
- Not part of the \`/cplan\` wave graph. Runtime-injected via \`c-thru --agents\` only.
`;
}

function renderAgentMd(entry, catalog, includeMarker = true) {
  const description = buildDescription(entry, catalog);
  const body = buildBody(entry);
  return [
    '---',
    `name: ${entry.id}`,
    `description: ${description}`,
    `model: ${entry.id}`,
    'tier_budget: 999999',
    '---',
    '',
    ...(includeMarker ? [GENERATED_MARKER, ''] : []),
    body,
  ].join('\n');
}

function hasGeneratedMarker(content) {
  return content.split(/\r?\n/).slice(0, 12).includes(GENERATED_MARKER);
}

function generatedAgentIds() {
  const ids = new Set();
  for (const file of fs.readdirSync(AGENTS_DIR)) {
    if (!file.endsWith('.md')) continue;
    const content = fs.readFileSync(path.join(AGENTS_DIR, file), 'utf8');
    if (hasGeneratedMarker(content)) ids.add(file.replace(/\.md$/, ''));
  }
  return ids;
}

function validate(catalog, map, entries) {
  const errors = [];
  const routes = map.model_routes || {};

  function routeCovers(model) {
    if (routes[model] !== undefined) return true;
    for (const k of Object.keys(routes)) {
      if (!k.startsWith('re:')) continue;
      try {
        if (new RegExp(k.slice(3)).test(model)) return true;
      } catch (_) { /* ignore bad re */ }
    }
    return false;
  }

  for (const e of entries) {
    if (!ID_RE.test(e.id)) {
      errors.push(`id '${e.id}' is not Claude-safe (need ${ID_RE})`);
    }
    if (typeof e.pin !== 'string' || !e.pin.startsWith('model:') || e.pin.length <= 'model:'.length) {
      errors.push(`${e.id}: pin must be model:<nonempty> (got ${JSON.stringify(e.pin)})`);
    } else {
      const bare = e.pin.slice('model:'.length);
      if (!routeCovers(bare)) {
        errors.push(`${e.id}: pin target '${bare}' not in model_routes (and no re: match)`);
      }
    }
    // A catalog entry may replace only a marked generated file. Byte-identical
    // pre-marker output is accepted once so existing catalogs can migrate safely.
    if (ID_RE.test(e.id)) {
      const dest = path.join(AGENTS_DIR, `${e.id}.md`);
      if (fs.existsSync(dest)) {
        const content = fs.readFileSync(dest, 'utf8');
        const isLegacyGenerated = content === renderAgentMd(e, catalog, false);
        if (!hasGeneratedMarker(content) && !isLegacyGenerated) {
          errors.push(`${e.id}: collides with non-generated agent file agents/${e.id}.md`);
        }
      }
    }
  }

  // Explicit named Claude leaves are vendor/model requests, not logical quality
  // classes. Keep the generic model_routes keys mode-conditional for ordinary
  // transport requests, while brand agents pin the current concrete Claude ID.
  const claudeBrandPins = {
    opus: 'model:claude-opus-5',
    sonnet: 'model:claude-sonnet-5',
    haiku: 'model:claude-haiku-4-5-20251001',
    fable: 'model:claude-fable-5',
  };
  for (const [name, expectedPin] of Object.entries(claudeBrandPins)) {
    const e = entries.find(x => x.id === name);
    if (e && e.pin !== expectedPin) {
      errors.push(`${name}: must pin current concrete Claude model ${expectedPin} (got ${e.pin})`);
    }
  }

  return errors;
}

function patchAgentToCapability(map, entries, staleGeneratedIds) {
  const a2c = { ...(map.agent_to_capability || {}) };
  for (const id of staleGeneratedIds) {
    delete a2c[id];
  }
  for (const e of entries) {
    a2c[e.id] = e.pin;
  }
  map.agent_to_capability = a2c;
  return map;
}

function main() {
  const catalog = loadJson(CATALOG_PATH);
  const map = loadJson(MAP_PATH);
  const entries = expandEntries(catalog);
  const catalogIds = new Set(entries.map(e => e.id));
  const staleGeneratedIds = [...generatedAgentIds()]
    .filter(id => !catalogIds.has(id))
    .sort();
  const errors = validate(catalog, map, entries);
  if (errors.length) {
    for (const e of errors) console.error('gen-brand-agents:', e);
    process.exit(1);
  }

  let drift = false;
  for (const e of entries) {
    const dest = path.join(AGENTS_DIR, `${e.id}.md`);
    const content = renderAgentMd(e, catalog);
    if (CHECK) {
      if (!fs.existsSync(dest) || fs.readFileSync(dest, 'utf8') !== content) {
        console.error(`gen-brand-agents --check: drift agents/${e.id}.md`);
        drift = true;
      }
    } else {
      fs.writeFileSync(dest, content);
    }
  }

  for (const id of staleGeneratedIds) {
    const dest = path.join(AGENTS_DIR, `${id}.md`);
    if (CHECK) {
      console.error(`gen-brand-agents --check: stale generated agents/${id}.md`);
      drift = true;
    } else {
      fs.unlinkSync(dest);
    }
  }

  const nextMap = patchAgentToCapability(
    JSON.parse(JSON.stringify(map)),
    entries,
    staleGeneratedIds,
  );
  const mapOut = JSON.stringify(nextMap, null, 2) + '\n';
  if (CHECK) {
    // Only require that every pin is present (map may have other WIP keys)
    for (const e of entries) {
      if ((map.agent_to_capability || {})[e.id] !== e.pin) {
        console.error(`gen-brand-agents --check: agent_to_capability['${e.id}'] expected ${e.pin}, got ${JSON.stringify((map.agent_to_capability || {})[e.id])}`);
        drift = true;
      }
    }
    for (const id of staleGeneratedIds) {
      if (Object.prototype.hasOwnProperty.call(map.agent_to_capability || {}, id)) {
        console.error(`gen-brand-agents --check: stale agent_to_capability['${id}']`);
        drift = true;
      }
    }
    if (fs.existsSync(PLUGIN_MAP_PATH)) {
      const pmap = loadJson(PLUGIN_MAP_PATH);
      for (const id of staleGeneratedIds) {
        if (Object.prototype.hasOwnProperty.call(pmap.agent_to_capability || {}, id)) {
          console.error(`gen-brand-agents --check: stale plugin agent_to_capability['${id}']`);
          drift = true;
        }
      }
    }
  } else {
    fs.writeFileSync(MAP_PATH, mapOut);
    if (fs.existsSync(PLUGIN_MAP_PATH)) {
      const pmap = loadJson(PLUGIN_MAP_PATH);
      pmap.agent_to_capability = nextMap.agent_to_capability;
      fs.writeFileSync(PLUGIN_MAP_PATH, JSON.stringify(pmap, null, 2) + '\n');
    }
  }

  if (CHECK) {
    if (drift) {
      console.error('gen-brand-agents --check: FAILED');
      process.exit(1);
    }
    console.log(`gen-brand-agents --check: ok (${entries.length} brand agents)`);
    return;
  }

  const removed = staleGeneratedIds.length
    ? `; removed ${staleGeneratedIds.length} stale generated agent(s)`
    : '';
  console.log(`gen-brand-agents: wrote ${entries.length} agents + agent_to_capability pins${removed}`);
}

main();

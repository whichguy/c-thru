function identityBlock(entry) {
  const fam = entry.family || entry.id;
  const info = FAMILY_IDENTITY[fam] || {
    maker: entry.label || entry.id,
    claim: entry.label || entry.id,
    forbid: 'Do not claim to be Claude, Anthropic, Sonnet, Opus, or Haiku unless that is your brand family.',
  };
  const isClaude = fam === 'anthropic-claude';
  // Do not embed concrete model tags (colons/dots) — agent-description-quality scans for them.
  return `## Identity (binding — overrides transport labels)

You are the **${entry.label}** brand leaf (family \`${fam}\`).
Claude Code / Anthropic transport wording is **not** your identity unless family is anthropic-claude.

When asked your model name, maker, origin, or "who are you":
- Identify as **${info.claim}**, made by **${info.maker}**.
- ${info.forbid}
- Answer in 1–3 short sentences as yourself only.
- Do not invent a different brand from the agent id alone if routing clearly failed; say routing failed.
${isClaude ? '- You may identify as Claude (Anthropic family).\n' : '- Never answer "I am Claude" / "I am Sonnet" / "built by Anthropic" for this leaf.\n'}`;
}

function buildBody(entry) {
  const aliasLine = entry.isAlias
    ? `\nThis is a **full-name alias** of the primary brand leaf for family **${entry.family}**.\n`
    : '';
  // Do not embed concrete model tags (colons/dots) in the body — agent-description-quality
  // treats them as model-id claims that must match the pin's resolution set.
  return `# Agent: ${entry.label} (\`${entry.id}\`)

You are the c-thru **named brand leaf** for **${entry.label}**.
Routing is via \`agent_to_capability\` model pin for this agent name (see config brand catalog).
${aliasLine}
## Hard constraints

- Complete the task in this turn; return the answer to the parent.
- Prefer to complete the task yourself; avoid spawning further Agent/Task subagents for the same question.
- Do not re-delegate the same question to another agent.
- Prefer opinion, critique, and short analysis over multi-file source patches. If the ask is
  clearly an implement/fix/review-loop contract, say so and return to the parent so they can
  route to \`coder\` instead of half-applying edits here.

${identityBlock(entry)}
## Strategy

- Treat the user question as a one-shot brief: goal, scope (paths if given), constraints, and
  what a good answer looks like.
- Not part of the \`/cplan\` wave graph. Runtime-injected via \`c-thru --agents\` only.
`;
}

function renderAgentMd(entry, catalog, includeMarker = true) {
  const description = buildDescription(entry, catalog);
  const body = buildBody(entry);
  return [
    '---',
    `name: ${entry.id}`,
    `description: ${description}`,
    `model: ${entry.id}`,
    'tier_budget: 999999',
    '---',
    '',
    ...(includeMarker ? [GENERATED_MARKER, ''] : []),
    body,
  ].join('\n');
}

function hasGeneratedMarker(content) {
  return content.split(/\r?\n/).slice(0, 12).includes(GENERATED_MARKER);
}

function generatedAgentIds() {
  const ids = new Set();
  for (const file of fs.readdirSync(AGENTS_DIR)) {
    if (!file.endsWith('.md')) continue;
    const snapshot = readFileSnapshot(path.join(AGENTS_DIR, file));
    if (snapshot.exists && hasGeneratedMarker(snapshot.content.toString('utf8'))) {
      ids.add(file.replace(/\.md$/, ''));
    }
  }
  return ids;
}

function agentCollision(entry, catalog, snapshot = null) {
  if (!ID_RE.test(entry.id)) return null;
  const dest = path.join(AGENTS_DIR, `${entry.id}.md`);
  const current = snapshot || readFileSnapshot(dest);
  if (!current.exists) return null;
  const content = current.content.toString('utf8');
  const isLegacyGenerated = content === renderAgentMd(entry, catalog, false);
  if (hasGeneratedMarker(content) || isLegacyGenerated) return null;
  return `${entry.id}: collides with non-generated agent file agents/${entry.id}.md`;
}

function readOwnership(map, label, errors) {
  if (!Object.prototype.hasOwnProperty.call(map, OWNERSHIP_KEY)) {
    return { present: false, ids: [] };
  }
  const value = map[OWNERSHIP_KEY];
  if (!Array.isArray(value)) {
    errors.push(`${label}.${OWNERSHIP_KEY}: must be an array of agent ids`);
    return { present: true, ids: [] };
  }
  const ids = [];
  const seen = new Set();
  for (const id of value) {
    if (typeof id !== 'string' || !ID_RE.test(id)) {
      errors.push(`${label}.${OWNERSHIP_KEY}: invalid agent id ${JSON.stringify(id)}`);
      continue;
    }
    if (seen.has(id)) {
      errors.push(`${label}.${OWNERSHIP_KEY}: duplicate agent id '${id}'`);
      continue;
    }
    seen.add(id);
    ids.push(id);
  }
  return { present: true, ids };
}

function hasNonGeneratedAgentFile(id) {
  const dest = path.join(AGENTS_DIR, `${id}.md`);
  return fs.existsSync(dest) && !hasGeneratedMarker(fs.readFileSync(dest, 'utf8'));
}

function staleMappingIds(staleOwnedIds) {
  // A same-name unmarked file means the id has been repurposed as a user/role
  // agent. Relinquish generated ownership without touching that agent's mapping.
  return staleOwnedIds.filter(id => !hasNonGeneratedAgentFile(id));
}

function readFileSnapshot(dest) {
  try {
    const stat = fs.statSync(dest);
    return {
      exists: true,
      content: fs.readFileSync(dest),
      mode: stat.mode & 0o777,
    };
  } catch (e) {
    if (e && e.code === 'ENOENT') {
      return { exists: false, content: null, mode: 0o666 };
    }
    throw e;
  }
}

function readMapSnapshot(dest) {
  const snapshot = readFileSnapshot(dest);
  if (!snapshot.exists) {
    const e = new Error(`required map ${path.relative(REPO, dest)} does not exist`);
    e.code = 'ENOENT';
    throw e;
  }
  const text = snapshot.content.toString('utf8');
  return { ...snapshot, text, map: JSON.parse(text) };
}

function snapshotsEqual(a, b) {
  if (a.exists !== b.exists) return false;
  if (!a.exists) return true;
  return a.mode === b.mode && a.content.equals(b.content);
}

function assertSnapshotUnchanged(dest, expected, label) {
  const current = readFileSnapshot(dest);
  if (!snapshotsEqual(current, expected)) {
    throw new Error(`${label} changed during generation; refusing to overwrite concurrent edits`);
  }
}

let tempSequence = 0;

function siblingTempPath(dest, kind) {
  tempSequence += 1;
  return path.join(
    path.dirname(dest),
    `.${path.basename(dest)}.gen-brand-agents.${process.pid}.${tempSequence}.${kind}`,
  );
}

function stageFile(dest, content, mode, kind) {
  const staged = siblingTempPath(dest, kind);
  fs.writeFileSync(staged, content, { flag: 'wx', mode });
  return staged;
}

function safeUnlink(dest) {
  try {
    fs.unlinkSync(dest);
  } catch (e) {
    if (!e || e.code !== 'ENOENT') throw e;
  }
}

function commitFileTransaction(mutations, guards) {
  const staged = [];
  const applied = [];

  try {
    // Prepare every replacement and rollback image before touching live files.
    for (const mutation of mutations) {
      if (mutation.after !== null) {
        mutation.stagePath = stageFile(
          mutation.dest,
          mutation.after,
          mutation.before.exists ? mutation.before.mode : 0o666,
          'stage',
        );
        staged.push(mutation.stagePath);
      }
      if (mutation.before.exists) {
        mutation.backupPath = stageFile(
          mutation.dest,
          mutation.before.content,
          mutation.before.mode,
          'backup',
        );
        staged.push(mutation.backupPath);
      }
    }

    // This is deliberately after staging: a concurrent map edit during an
    // expensive render/stage phase aborts while every live artifact is intact.
    for (const guard of guards) {
      assertSnapshotUnchanged(guard.dest, guard.snapshot, guard.label);
    }

    try {
      for (const mutation of mutations) {
        // Narrow the remaining compare/rename window for each live target.
        assertSnapshotUnchanged(mutation.dest, mutation.before, mutation.label);
        if (mutation.after === null) {
          fs.unlinkSync(mutation.dest);
        } else {
          fs.renameSync(mutation.stagePath, mutation.dest);
        }
        applied.push(mutation);
      }
    } catch (commitError) {
      const rollbackErrors = [];
      for (const mutation of applied.reverse()) {
        try {
          if (mutation.before.exists) {
            fs.renameSync(mutation.backupPath, mutation.dest);
          } else {
            safeUnlink(mutation.dest);
          }
        } catch (rollbackError) {
          rollbackErrors.push(`${mutation.label}: ${rollbackError.message}`);
        }
      }
      if (rollbackErrors.length) {
        throw new Error(
          `transaction commit failed (${commitError.message}); rollback also failed: ${rollbackErrors.join('; ')}`,
        );
      }
      throw new Error(`transaction commit failed and was rolled back: ${commitError.message}`);
    }
  } finally {
    for (const tempPath of staged) {
      try { safeUnlink(tempPath); } catch (_) { /* original error is more useful */ }
    }
  }
}

function ownershipMatches(ownership, expectedIds) {
  if (!ownership.present) return false;
  return JSON.stringify([...ownership.ids].sort()) === JSON.stringify(expectedIds);
}

function validate(catalog, map, entries) {
  const errors = [];
  const routes = map.model_routes || {};

  function routeCovers(model) {
    if (routes[model] !== undefined) return true;
    // Shorthand pin model:fable → latest_models.fable → concrete route
    const latest = (map.latest_models || {})[model];
    if (typeof latest === 'string' && latest && routes[latest] !== undefined) return true;
    for (const k of Object.keys(routes)) {
      if (!k.startsWith('re:')) continue;
      try {
        if (new RegExp(k.slice(3)).test(model)) return true;
      } catch (_) { /* ignore bad re */ }
    }
    return false;
  }

  for (const e of entries) {
    if (!ID_RE.test(e.id)) {
      errors.push(`id '${e.id}' is not Claude-safe (need ${ID_RE})`);
    }
    if (typeof e.pin !== 'string' || !e.pin.startsWith('model:') || e.pin.length <= 'model:'.length) {
      errors.push(`${e.id}: pin must be model:<nonempty> (got ${JSON.stringify(e.pin)})`);
    } else {
      const bare = e.pin.slice('model:'.length);
      if (!routeCovers(bare)) {
        errors.push(`${e.id}: pin target '${bare}' not in model_routes/latest_models (and no re: match)`);
      }
    }
    // A catalog entry may replace only a marked generated file. Byte-identical
    // pre-marker output is accepted once so existing catalogs can migrate safely.
    const collision = agentCollision(e, catalog);
    if (collision) errors.push(collision);
  }

  // Named Claude leaves pin the public shorthand (model:opus / model:fable).
  // Proxy latest_models expands to the current concrete Anthropic id — never
  // mode-remap the short name to OSS under a different vendor.
  const claudeShorthands = ['opus', 'sonnet', 'haiku', 'fable'];
  for (const name of claudeShorthands) {
    const e = entries.find(x => x.id === name);
    if (!e) continue;
    const expectedPin = (map.latest_models && map.latest_models[name])
      ? `model:${name}`
      : null;
    if (expectedPin && e.pin !== expectedPin) {
      errors.push(`${name}: must pin shorthand ${expectedPin} (latest via latest_models; got ${e.pin})`);
    }
  }

  return errors;
}

function patchAgentToCapability(map, entries, staleGeneratedIds, ownershipIds) {
  const a2c = { ...(map.agent_to_capability || {}) };
  for (const id of staleGeneratedIds) {
    delete a2c[id];
  }
  for (const e of entries) {
    a2c[e.id] = e.pin;
  }
  map.agent_to_capability = a2c;
  map[OWNERSHIP_KEY] = ownershipIds;
  return map;
}

function main() {
  const catalogSnapshot = readFileSnapshot(CATALOG_PATH);
  if (!catalogSnapshot.exists) throw new Error('config/brand-agents.json does not exist');
  const catalog = JSON.parse(catalogSnapshot.content.toString('utf8'));
  const mapSnapshot = readMapSnapshot(MAP_PATH);
  const pluginFileSnapshot = readFileSnapshot(PLUGIN_MAP_PATH);
  const pluginSnapshot = pluginFileSnapshot.exists
    ? {
      ...pluginFileSnapshot,
      text: pluginFileSnapshot.content.toString('utf8'),
      map: JSON.parse(pluginFileSnapshot.content.toString('utf8')),
    }
    : null;
  const map = mapSnapshot.map;
  const entries = expandEntries(catalog);
  const catalogIds = new Set(entries.map(e => e.id));
  const expectedOwnershipIds = [...catalogIds].sort();
  const markedIds = generatedAgentIds();
  const errors = validate(catalog, map, entries);
  const mapOwnership = readOwnership(map, 'config/model-map.json', errors);
  const pluginOwnership = pluginSnapshot
    ? readOwnership(pluginSnapshot.map, 'plugins/c-thru/config/model-map.json', errors)
    : { present: false, ids: [] };
  const ownedIds = new Set([
    ...markedIds,
    ...mapOwnership.ids,
    ...pluginOwnership.ids,
  ]);
  const staleOwnedIds = [...ownedIds]
    .filter(id => !catalogIds.has(id))
    .sort();
  const staleMarkedIds = [...markedIds]
    .filter(id => !catalogIds.has(id))
    .sort();
  if (errors.length) {
    for (const e of errors) console.error('gen-brand-agents:', e);
    process.exit(1);
  }

  let drift = false;
  if (CHECK) {
    for (const e of entries) {
      const dest = path.join(AGENTS_DIR, `${e.id}.md`);
      const snapshot = readFileSnapshot(dest);
      const content = renderAgentMd(e, catalog);
      if (!snapshot.exists || snapshot.content.toString('utf8') !== content) {
        console.error(`gen-brand-agents --check: drift agents/${e.id}.md`);
        drift = true;
      }
    }

    for (const id of staleMarkedIds) {
      console.error(`gen-brand-agents --check: stale generated agents/${id}.md`);
      drift = true;
    }

    const ownershipRequired = expectedOwnershipIds.length > 0 || markedIds.size > 0 ||
      mapOwnership.present || pluginOwnership.present;
    if (ownershipRequired && !ownershipMatches(mapOwnership, expectedOwnershipIds)) {
      console.error(`gen-brand-agents --check: drift config/model-map.json ${OWNERSHIP_KEY}`);
      drift = true;
    }
    if (ownershipRequired && pluginSnapshot && !ownershipMatches(pluginOwnership, expectedOwnershipIds)) {
      console.error(`gen-brand-agents --check: drift plugins/c-thru/config/model-map.json ${OWNERSHIP_KEY}`);
      drift = true;
    }

    // Only require that every pin is present (map may have other WIP keys)
    for (const e of entries) {
      if ((map.agent_to_capability || {})[e.id] !== e.pin) {
        console.error(`gen-brand-agents --check: agent_to_capability['${e.id}'] expected ${e.pin}, got ${JSON.stringify((map.agent_to_capability || {})[e.id])}`);
        drift = true;
      }
    }
    const staleMappings = staleMappingIds(staleOwnedIds);
    for (const id of staleMappings) {
      if (Object.prototype.hasOwnProperty.call(map.agent_to_capability || {}, id)) {
        console.error(`gen-brand-agents --check: stale agent_to_capability['${id}']`);
        drift = true;
      }
    }
    if (pluginSnapshot) {
      for (const id of staleMappings) {
        if (Object.prototype.hasOwnProperty.call(pluginSnapshot.map.agent_to_capability || {}, id)) {
          console.error(`gen-brand-agents --check: stale plugin agent_to_capability['${id}']`);
          drift = true;
        }
      }
    }
    if (drift) {
      console.error('gen-brand-agents --check: FAILED');
      process.exit(1);
    }
    console.log(`gen-brand-agents --check: ok (${entries.length} brand agents)`);
    return;
  }

  // Capture every agent destination before constructing outputs. The same
  // snapshots are guards for the commit, so a repurposed role or generated
  // file changed while staging cannot be overwritten or deleted.
  const agentSnapshots = new Map();
  function agentSnapshot(id) {
    if (!agentSnapshots.has(id)) {
      agentSnapshots.set(id, readFileSnapshot(path.join(AGENTS_DIR, `${id}.md`)));
    }
    return agentSnapshots.get(id);
  }
  for (const e of entries) agentSnapshot(e.id);
  for (const id of staleOwnedIds) agentSnapshot(id);

  for (const e of entries) {
    const collision = agentCollision(e, catalog, agentSnapshot(e.id));
    if (collision) {
      throw new Error(`${collision}; changed during generation, refusing to overwrite`);
    }
  }

  const staleMappings = staleOwnedIds.filter(id => {
    const snapshot = agentSnapshot(id);
    return !snapshot.exists || hasGeneratedMarker(snapshot.content.toString('utf8'));
  });
  const mutations = [];

  function addMutation(dest, label, before, after) {
    const next = after === null || Buffer.isBuffer(after) ? after : Buffer.from(after);
    if (next !== null && before.exists && before.content.equals(next)) return;
    if (next === null && !before.exists) return;
    mutations.push({ dest, label, before, after: next });
  }

  for (const e of entries) {
    const dest = path.join(AGENTS_DIR, `${e.id}.md`);
    addMutation(
      dest,
      `agents/${e.id}.md`,
      agentSnapshot(e.id),
      renderAgentMd(e, catalog),
    );
  }

  let removedAgentCount = 0;
  for (const id of staleMarkedIds) {
    const snapshot = agentSnapshot(id);
    if (!snapshot.exists || !hasGeneratedMarker(snapshot.content.toString('utf8'))) continue;
    addMutation(path.join(AGENTS_DIR, `${id}.md`), `agents/${id}.md`, snapshot, null);
    removedAgentCount += 1;
  }

  const nextMap = patchAgentToCapability(
    JSON.parse(mapSnapshot.text),
    entries,
    staleMappings,
    expectedOwnershipIds,
  );
  addMutation(
    MAP_PATH,
    'config/model-map.json',
    mapSnapshot,
    JSON.stringify(nextMap, null, 2) + '\n',
  );

  if (pluginSnapshot) {
    const nextPluginMap = JSON.parse(pluginSnapshot.text);
    nextPluginMap.agent_to_capability = nextMap.agent_to_capability;
    nextPluginMap[OWNERSHIP_KEY] = expectedOwnershipIds;
    addMutation(
      PLUGIN_MAP_PATH,
      'plugins/c-thru/config/model-map.json',
      pluginSnapshot,
      JSON.stringify(nextPluginMap, null, 2) + '\n',
    );
  }

  const guards = [
    { dest: CATALOG_PATH, snapshot: catalogSnapshot, label: 'config/brand-agents.json' },
    { dest: MAP_PATH, snapshot: mapSnapshot, label: 'config/model-map.json' },
    {
      dest: PLUGIN_MAP_PATH,
      snapshot: pluginSnapshot || pluginFileSnapshot,
      label: 'plugins/c-thru/config/model-map.json',
    },
    ...[...agentSnapshots.entries()].map(([id, snapshot]) => ({
      dest: path.join(AGENTS_DIR, `${id}.md`),
      snapshot,
      label: `agents/${id}.md`,
    })),
  ];
  commitFileTransaction(mutations, guards);

  const removed = removedAgentCount
    ? `; removed ${removedAgentCount} stale generated agent(s)`
    : '';
  console.log(`gen-brand-agents: wrote ${entries.length} agents + agent_to_capability pins${removed}`);
}

try {
  acquireGeneratorLock();
  main();
} catch (e) {
  console.error(`gen-brand-agents: ${e && e.message || e}`);
  process.exitCode = 1;
}

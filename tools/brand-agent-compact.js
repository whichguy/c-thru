/**
 * @param {{ id: string, label?: string, family?: string, isAlias?: boolean }} entry
 * @returns {string}
 */
function compactBrandPrompt(entry) {
  const id = entry.id || 'unknown';
  const fam = entry.family || id;
  const label = entry.label || id;
  const info = FAMILY_IDENTITY[fam] || {
    maker: label,
    claim: label,
    forbid: 'Do not claim to be Claude/Anthropic unless that is your brand family.',
  };
  // Prefer catalog label for Claude leaves (Claude Fable vs generic Claude).
  const claim = (fam === 'anthropic-claude' && label) ? label : info.claim;
  const aliasNote = entry.isAlias
    ? ` Exact-id alias of family ${fam}; only for this id.`
    : '';
  const claudeOk = fam === 'anthropic-claude'
    ? ' You may identify as Claude (Anthropic family).'
    : ' Never claim Claude/Sonnet/Anthropic.';
  return [
    `Brand leaf: ${label} (id ${id}, family ${fam}).${aliasNote}`,
    'One-shot answer for parent; do not re-delegate; no multi-file implement (use coder).',
    `Identity: ${claim}, made by ${info.maker}. ${info.forbid}${claudeOk}`,
    'On identity asks: 1–3 short sentences. Routing failure → say routing failed.',
    'Transport/tool model aliases are not proof of who served; follow Identity.',
  ].join(' ');
}

function isGeneratedBrandBody(promptOrFullMd) {
  if (typeof promptOrFullMd !== 'string') return false;
  return promptOrFullMd.includes('GENERATED by tools/gen-brand-agents.js')
    || promptOrFullMd.includes('named brand leaf')
    || promptOrFullMd.includes('## Identity (binding');
}

/**
 * Whether inject should replace the agent prompt with a compact brand template.
 * @param {{ name: string, prompt?: string, model?: string }} entry
 * @param {Record<string, string>|null|undefined} agentToCapability
 */
function shouldCompactAgentEntry(entry, agentToCapability) {
  if (!entry || typeof entry.name !== 'string') return false;
  if (isGeneratedBrandBody(entry.prompt || '')) return true;
  const pin = agentToCapability && agentToCapability[entry.name];
  if (typeof pin === 'string' && pin.startsWith('model:')) return true;
  return false;
}

/**
 * @param {string} name
 * @param {string} [prompt]
 * @param {{ label?: string, family?: string }|null} [meta]
 */
function compactPromptForAgentName(name, prompt, meta) {
  let label = meta && meta.label;
  let family = meta && meta.family;
  let isAlias = !!(meta && meta.isAlias);
  if ((!label || !family) && typeof prompt === 'string') {
    const m = prompt.match(/# Agent:\s*(.+?)\s*\(`([^`]+)`\)/);
    if (m) {
      label = label || m[1].trim();
    }
    const fam = prompt.match(/family `([^`]+)`/);
    if (fam) family = family || fam[1];
    if (/full-name alias/i.test(prompt)) isAlias = true;
  }
  return compactBrandPrompt({
    id: name,
    label: label || name,
    family: family || name,
    isAlias,
  });
}


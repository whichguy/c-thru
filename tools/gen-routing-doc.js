#!/usr/bin/env node
'use strict';
// gen-routing-doc.js — regenerate the README "Agent routing reference" table from config.
//
// The table is a derived artifact of config/model-map.json (agent_to_capability +
// llm_profiles) — it WILL silently drift on the next config bump unless it is generated
// and verified. This wraps `tools/c-thru-explain.js --all` (the same resolver the proxy
// uses — no reimplemented routing) and rewrites the region between the sentinel markers
// in README.md.
//
//   node tools/gen-routing-doc.js            # rewrite the marked region in place
//   node tools/gen-routing-doc.js --check     # exit 1 + print a diff if README is stale
//
// Determinism: explain() is pinned to the repo's config/model-map.json via
// CLAUDE_MODEL_MAP_PATH so it never reads the runtime ~/.claude/model-map.json (which the
// proxy regenerates and a user may have overridden). Mirrors sync-plugin-bundle.sh --check.

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const REPO_ROOT = path.join(__dirname, '..');
const EXPLAIN = path.join(__dirname, 'c-thru-explain.js');
const CONFIG = path.join(REPO_ROOT, 'config', 'model-map.json');
const README = path.join(REPO_ROOT, 'README.md');

// Columns are the three primary routing modes; models shown at the reference tier 64gb;
// endpoint column is for mode best-cloud (table column only — product default mode is best-cloud-oss).
const MODES = ['best-cloud', 'best-cloud-oss', 'best-local-oss'];
const ENDPOINT_MODE = 'best-cloud';
const TIER = '64gb';
const PASSTHROUGH = new Set(['WebSearch', 'WebFetch', 'Monitor']);

const BEGIN = '<!-- BEGIN routing-table (generated by tools/gen-routing-doc.js — run it, don\'t hand-edit) -->';
const END = '<!-- END routing-table -->';

function explain(mode) {
  const out = execFileSync('node', [EXPLAIN, '--all', '--mode', mode, '--tier', TIER, '--format', 'json'], {
    env: { ...process.env, CLAUDE_MODEL_MAP_PATH: CONFIG },
    encoding: 'utf8',
    maxBuffer: 16 * 1024 * 1024,
  });
  const rows = JSON.parse(out);
  const byCap = new Map();
  for (const r of rows) byCap.set(r.capability, r);
  return byCap;
}

function buildTable() {
  const config = JSON.parse(fs.readFileSync(CONFIG, 'utf8'));
  const a2c = config.agent_to_capability || {};

  const perMode = {};
  for (const m of MODES) perMode[m] = explain(m);
  const endpoints = perMode[ENDPOINT_MODE];

  const agents = Object.keys(a2c).filter((a) => !PASSTHROUGH.has(a)).sort();

  const lines = [];
  lines.push('| Agent | Capability | `best-cloud` | `best-cloud-oss` | `best-local-oss` | Endpoint (`best-cloud`) |');
  lines.push('|---|---|---|---|---|---|');
  for (const agent of agents) {
    const cap = a2c[agent];
    const remap = agent !== cap;
    const nameCell = '`' + agent + '`' + (remap ? ' &nbsp;⚠' : '');
    const cells = MODES.map((m) => {
      const row = perMode[m].get(cap);
      return '`' + (row ? row.model : '—') + '`';
    });
    const ep = endpoints.get(cap);
    const epCell = '`' + (ep ? ep.endpoint_id : '—') + '`';
    lines.push(`| ${nameCell} | \`${cap}\` | ${cells.join(' | ')} | ${epCell} |`);
  }
  return lines.join('\n');
}

function spliceRegion(readme, table) {
  const b = readme.indexOf(BEGIN);
  const e = readme.indexOf(END);
  if (b === -1 || e === -1 || e < b) {
    console.error(`gen-routing-doc: sentinel markers not found in README.md.\n  Expected:\n    ${BEGIN}\n    ${END}`);
    process.exit(2);
  }
  const before = readme.slice(0, b + BEGIN.length);
  const after = readme.slice(e);
  return `${before}\n${table}\n${after}`;
}

function main() {
  const check = process.argv.includes('--check');
  const readme = fs.readFileSync(README, 'utf8');
  const table = buildTable();
  const next = spliceRegion(readme, table);

  if (check) {
    if (next === readme) {
      console.log('gen-routing-doc: README routing table is up to date.');
      return;
    }
    console.error('gen-routing-doc: README routing table is STALE (config changed but the table was not regenerated).');
    // Minimal line-level diff of the marked region for readability.
    const region = (s) => s.slice(s.indexOf(BEGIN), s.indexOf(END) + END.length).split('\n');
    const cur = region(readme), gen = region(next);
    const max = Math.max(cur.length, gen.length);
    for (let i = 0; i < max; i++) {
      if (cur[i] !== gen[i]) {
        if (cur[i] !== undefined) console.error(`  - ${cur[i]}`);
        if (gen[i] !== undefined) console.error(`  + ${gen[i]}`);
      }
    }
    console.error('\nRun: node tools/gen-routing-doc.js');
    process.exit(1);
  }

  if (next === readme) {
    console.log('gen-routing-doc: README routing table already current — no change.');
    return;
  }
  fs.writeFileSync(README, next);
  console.log('gen-routing-doc: regenerated README routing table.');
}

main();
